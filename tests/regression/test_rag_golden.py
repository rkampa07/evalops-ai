"""Replays the recorded local-model answers and judge verdicts through the API.

The responses in examples/rag/responses were generated by Qwen2.5-1.5B-Instruct (4-bit, MLX)
and the verdicts in examples/rag/grades by Llama-3.2-3B-Instruct (4-bit, MLX); see
docs/rag-evaluation.md. Scoring them is deterministic, so these numbers are pinned: a change in
the RAG methodology that moves them must be deliberate.
"""

import json
from pathlib import Path

import pytest

RAG = Path(__file__).resolve().parents[2] / "examples/rag"


def load(rel):
    return json.loads((RAG / rel).read_text())


@pytest.fixture()
def rag_runs(client):
    kb = load("kestrel_policy_kb.json")
    ds = client.post("/datasets", json={"name": kb["name"]}).json()
    client.post(f"/datasets/{ds['id']}/passages", json={"passages": kb["passages"]})
    client.post(f"/datasets/{ds['id']}/test-cases/bulk", json={"test_cases": kb["test_cases"]})
    runs = {}
    for version in ("rag-v1", "rag-v2", "rag-v3"):
        record = load(f"responses/qwen2.5-1.5b_{version}.json")
        body = {
            k: record[k] for k in ("model_name", "prompt_version", "label", "config", "generation")
        }
        r = client.post(
            "/evaluations/runs",
            json=body | {"dataset_id": ds["id"], "responses": record["responses"]},
        )
        assert r.status_code == 201, r.text
        grades = load(f"grades/llama3.2-3b_judge-v2_on_qwen-{version}.json")
        g = client.put(
            f"/evaluations/runs/{r.json()['id']}/model-grades",
            json={"judge": grades["judge"], "grades": grades["grades"]},
        )
        assert g.status_code == 200, g.text
        runs[version] = g.json()
    return runs


GOLDEN = {
    "rag-v1": {"passed_cases": 9, "groundedness": 0.777778, "abstention_accuracy": 0.9,
               "citation_validity_rate": 0.9, "retrieval_recall_at_k": 0.852941,
               "unsupported_claim_count": 4, "estimated_groundedness": 0.444444},
    "rag-v2": {"passed_cases": 3, "groundedness": 0.521739, "abstention_accuracy": 0.85,
               "citation_validity_rate": 0.916667, "retrieval_recall_at_k": 0.852941,
               "unsupported_claim_count": 22, "estimated_groundedness": 0.304348},
    "rag-v3": {"passed_cases": 9, "groundedness": 0.8, "abstention_accuracy": 0.85,
               "citation_validity_rate": 1.0, "retrieval_recall_at_k": 0.852941,
               "unsupported_claim_count": 6, "estimated_groundedness": 0.533333},
}  # fmt: skip


@pytest.mark.parametrize("version", list(GOLDEN))
def test_recorded_answers_score_as_pinned(rag_runs, version):
    run = rag_runs[version]
    expected = GOLDEN[version]
    for key in expected:
        if key == "estimated_groundedness":
            assert run["model_graded"][key] == pytest.approx(expected[key], abs=1e-6)
        else:
            assert run["summary"][key] == pytest.approx(expected[key], abs=1e-6), key
    assert run["generation"]["model_id"] == "mlx-community/Qwen2.5-1.5B-Instruct-4bit"
    assert run["generation"]["model_revision"]
    assert run["model_graded"]["label"] == "estimated"


def test_candidate_prompt_regression_detected_and_gated(client, rag_runs):
    b, c = rag_runs["rag-v1"]["id"], rag_runs["rag-v2"]["id"]
    cmp = client.get(
        "/evaluations/compare", params={"baseline_run_id": b, "candidate_run_id": c}
    ).json()
    assert cmp["compatible"] and cmp["has_regression"]
    assert cmp["case_counts"]["regressed"] == 7
    statuses = {d["metric"]: d["status"] for d in cmp["metric_deltas"]}
    assert statuses["groundedness"] == "regressed"
    assert statuses["abstention_accuracy"] == "regressed"
    (est,) = cmp["estimated_metric_deltas"]
    assert est["status"] == "regressed"
    changes = {x["case_key"]: x["change"] for x in cmp["case_changes"]}
    # the candidate invents answers to all three unanswerable questions
    for key in ("q-showroom-hours", "q-gift-wrap", "q-financing"):
        assert changes[key] == "regressed"

    rep = client.get(f"/evaluations/runs/{c}/report", params={"baseline_run_id": b}).json()
    assert rep["readiness"] == "not_ready"
    failed = {g["gate"] for g in rep["gate_evaluation"]["gates"] if g["status"] == "fail"}
    assert {"min_groundedness", "max_regressed_cases", "min_abstention_accuracy"} <= failed


def test_rag_v3_improves_evidence_but_still_fails_the_predefined_gates(client, rag_runs):
    """rag-v3 was written once to fix rag-v1's failures. It improves citations and lexical
    groundedness, but answers all three unanswerable questions, so it is NOT release-ready."""
    b, c = rag_runs["rag-v1"]["id"], rag_runs["rag-v3"]["id"]
    cmp = client.get(
        "/evaluations/compare", params={"baseline_run_id": b, "candidate_run_id": c}
    ).json()
    regressed = {x["case_key"] for x in cmp["case_changes"] if x["change"] == "regressed"}
    assert regressed == {"q-showroom-hours", "q-gift-wrap", "q-financing"}
    statuses = {d["metric"]: d["status"] for d in cmp["metric_deltas"]}
    assert statuses["citation_validity_rate"] == "improved"
    assert statuses["abstention_accuracy"] == "regressed"

    rep = client.get(f"/evaluations/runs/{c}/report", params={"baseline_run_id": b}).json()
    gates = {g["gate"]: g["status"] for g in rep["gate_evaluation"]["gates"]}
    assert rep["readiness"] == "not_ready"
    assert gates["min_citation_validity"] == "pass" and gates["min_groundedness"] == "pass"
    assert gates["min_abstention_accuracy"] == "fail" and gates["max_regressed_cases"] == "fail"


def test_degenerate_rag_v3_answer_fails_content_check(rag_runs):
    result = next(r for r in rag_runs["rag-v3"]["results"] if r["case_key"] == "q-opened-mattress")
    assert result["passed"] is False
    assert [f["check"] for f in result["failures"]] == ["content"]
